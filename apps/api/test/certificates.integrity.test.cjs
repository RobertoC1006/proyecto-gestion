require('reflect-metadata');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
const { mkdtemp, mkdir, readFile, writeFile, rename, stat, rm } = require('node:fs/promises');
const { join } = require('node:path');
const { tmpdir } = require('node:os');
const { CertificatesService } = require('../dist/certificates/certificates.service');

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const unavailable = {
  code: 'CERTIFICATE_FILE_UNAVAILABLE',
  message: 'El PDF original no está disponible. La emisión y su huella se conservan para verificar el archivo original.',
};

// In-memory transaction and write spies only. All files belong to this fixture's
// fresh OS-temp directory; no real database or application storage is inspected.
async function fixture(t, sentinel = false) {
  const root = await mkdtemp(join(tmpdir(), 'campusitsm-integrity-'));
  const previousFiles = process.env.FILES_DIR;
  process.env.FILES_DIR = join(root, sentinel ? 'sentinel' : 'files');
  t.after(async () => {
    try { await rm(root, { recursive: true, force: true }); }
    finally {
      if (previousFiles === undefined) delete process.env.FILES_DIR;
      else process.env.FILES_DIR = previousFiles;
    }
  });
  const sentinelBytes = Buffer.from('Sentinel: never replace this regular file.');
  if (sentinel) await writeFile(process.env.FILES_DIR, sentinelBytes);
  const actor = { id: randomUUID(), institutionId: randomUUID(), role: 'estudiante', active: true, permissions: [] };
  const ticket = {
    id: randomUUID(), institutionId: actor.institutionId, ownerId: actor.id,
    code: 'INC-2026-INTEGRITY', service: 'equipos', status: 'resuelto', failureConfirmed: true,
    createdAt: new Date('2026-11-20T08:00:00Z'), resolvedAt: new Date('2026-11-20T10:00:00Z'),
    owner: { displayName: 'Titular original' },
  };
  const matches = (row, where) => row && Object.entries(where).every(([key, value]) => row[key] === value);
  const writes = { certificates: [], audit: [] };
  const commits = [];
  let committed;
  const read = (row, { where, include }) => matches(row, where)
    ? { ...row, ...(include?.owner ? { owner: ticket.owner } : {}) } : null;
  const db = {
    certificate: {
      findFirst: async query => read(committed, query),
      findUnique: async query => read(committed, query),
      findMany: async ({ where }) => matches(committed, where) ? [{ ...committed }] : [],
      update: async ({ data }) => {
        writes.certificates.push({ operation: 'update', data });
        committed = { ...committed, ...data };
        return { ...committed };
      },
    },
    ticket: {
      findMany: async ({ where }) => matches(ticket, where) ? [{ ...ticket, certificate: committed ?? null }] : [],
    },
    certificateVerification: {
      create: async ({ data }) => { writes.audit.push({ ...data }); return { id: randomUUID(), ...data }; },
    },
    $transaction: async callback => {
      let staged = committed;
      const result = await callback({
        $queryRaw: async () => [],
        ticket: { findFirst: async ({ where }) => matches(ticket, where) ? { ...ticket } : null },
        institution: { findUnique: async () => ({ name: 'Institución original' }) },
        certificate: {
          findUnique: async query => read(staged, query),
          create: async ({ data }) => {
            writes.certificates.push({ operation: 'create', data });
            staged = { id: randomUUID(), ...data };
            return { ...staged };
          },
        },
      });
      // Simulated commit: generated bytes must already exist and match the issued
      // hash. A callback/file error leaves the previously published row untouched.
      const path = join(process.env.FILES_DIR, staged.storageKey);
      const bytes = await readFile(path);
      assert.equal(hash(bytes), staged.sha256, 'Commit requires the exact original bytes');
      committed = staged;
      commits.push({ path, bytes });
      return result;
    },
  };
  const service = new CertificatesService(db);
  const publicState = async code => ({ mine: await service.mine(actor), lookup: await service.publicLookup(code) });
  return { root, actor, ticket, service, writes, commits, publicState, sentinelBytes };
}

function rejectsHttp(operation, status, body) {
  return assert.rejects(operation, error => {
    assert.equal(error.getStatus(), status);
    assert.deepEqual(error.getResponse(), body);
    return true;
  });
}

test('Initial file failure rolls back publication; retry commits only after original bytes exist', async t => {
  const f = await fixture(t, true);
  const sentinelPath = process.env.FILES_DIR;
  const before = await f.service.mine(f.actor);
  await assert.rejects(() => f.service.issue(f.actor, f.ticket.id), error => error.code === 'ENOTDIR');
  assert.deepEqual(await f.service.mine(f.actor), before);
  assert.deepEqual((await f.service.mine(f.actor)).issued, []);
  assert.equal(f.commits.length, 0);
  assert.deepEqual(f.writes.audit, []);
  assert.deepEqual(await readFile(sentinelPath), f.sentinelBytes);

  process.env.FILES_DIR = join(f.root, 'usable');
  const issued = await f.service.issue(f.actor, f.ticket.id);
  assert.equal(f.commits.length, 1);
  assert.equal(hash(f.commits[0].bytes), issued.sha256);
  const download = await f.service.download(f.actor, issued.id);
  assert.deepEqual(download.bytes, f.commits[0].bytes);
  assert.deepEqual((await f.service.mine(f.actor)).issued, [issued]);
  assert.deepEqual(await readFile(sentinelPath), f.sentinelBytes);
  assert.deepEqual(f.writes.audit, []);
});

test('Missing, empty and directory faults preserve the original issuance and write spies', async t => {
  const f = await fixture(t);
  const issued = await f.service.issue(f.actor, f.ticket.id);
  const original = await f.service.download(f.actor, issued.id);
  const before = await f.publicState(issued.code);
  const beforeWrites = structuredClone(f.writes);
  const path = f.commits[0].path;
  for (const fault of ['missing', 'empty', 'directory']) {
    await rename(path, path + '.original');
    try {
      if (fault === 'empty') await writeFile(path, Buffer.alloc(0));
      if (fault === 'directory') await mkdir(path);
      for (const operation of [
        () => f.service.issue(f.actor, f.ticket.id),
        () => f.service.detail(f.actor, issued.id),
        () => f.service.download(f.actor, issued.id),
      ]) {
        await rejectsHttp(operation, 503, unavailable);
        assert.deepEqual(await f.publicState(issued.code), before);
        assert.deepEqual(f.writes, beforeWrites);
        assert.equal(f.commits.length, 1);
        if (fault === 'missing') await assert.rejects(readFile(path), { code: 'ENOENT' });
        if (fault === 'empty') assert.deepEqual(await readFile(path), Buffer.alloc(0));
        if (fault === 'directory') assert.equal((await stat(path)).isDirectory(), true);
      }
    } finally {
      // Remove only the injected fault, keeping the original backup immutable.
      if (fault !== 'missing') await rm(path, { recursive: true, force: true });
      await rename(path + '.original', path);
    }
    assert.deepEqual((await f.service.download(f.actor, issued.id)).bytes, original.bytes);
    assert.deepEqual(await f.service.detail(f.actor, issued.id), issued);
    assert.deepEqual(await f.service.issue(f.actor, f.ticket.id), issued);
    assert.deepEqual(f.writes, beforeWrites);
  }
  assert.deepEqual(await f.service.verifyPdf(issued.code, original.bytes.toString('base64')),
    { code: issued.code, status: 'valida', sha256Matches: true });
  assert.deepEqual(f.writes.certificates, beforeWrites.certificates);
  assert.deepEqual(f.writes.audit, [{ institutionId: f.actor.institutionId, certificateId: issued.id, code: issued.code, result: 'valida' }]);
  assert.deepEqual(await f.publicState(issued.code), before);
});

test('Malformed identifiers and foreign owner/tenant reject without changing issuance or audit', async t => {
  const f = await fixture(t);
  const issued = await f.service.issue(f.actor, f.ticket.id);
  const original = await f.service.download(f.actor, issued.id);
  const before = await f.publicState(issued.code);
  const beforeWrites = structuredClone(f.writes);
  for (const [method, field] of [['issue', 'ticketId'], ['detail', 'id'], ['download', 'id']]) {
    await rejectsHttp(() => f.service[method](f.actor, 'not-a-uuid'), 400, {
      code: 'VALIDATION_ERROR', message: 'Revisa los campos indicados.', fields: { [field]: 'Selecciona un valor válido.' },
    });
    assert.deepEqual(await f.publicState(issued.code), before);
    assert.deepEqual(f.writes, beforeWrites);
  }
  for (const actor of [{ ...f.actor, id: randomUUID() }, { ...f.actor, institutionId: randomUUID() }]) {
    await rejectsHttp(() => f.service.issue(actor, f.ticket.id), 404,
      { code: 'CERTIFICATE_NOT_ELIGIBLE', message: 'El ticket no está disponible para emitir una constancia.' });
    for (const method of ['detail', 'download']) {
      await rejectsHttp(() => f.service[method](actor, issued.id), 404,
        { code: 'NOT_FOUND', message: 'No se encontró la constancia.' });
    }
    assert.deepEqual(await f.publicState(issued.code), before);
    assert.deepEqual(f.writes, beforeWrites);
  }
  assert.equal(f.commits.length, 1);
  assert.deepEqual((await f.service.download(f.actor, issued.id)).bytes, original.bytes);
});
